/// 评价一道题的作答。
pub(crate) fn question_task(group: &QuestionGroup<'_>, transcript: &[Segment]) -> String {
    // 和转写里一样用短编号
    let alias = |segment: &Segment| {
        transcript
            .iter()
            .position(|s| s.id == segment.id)
            .map(segment_alias)
    };
    let range = group
        .segments
        .first()
        .zip(group.segments.last())
        .and_then(|(first, last)| alias(first).zip(alias(last)));
    let segments = match range {
        Some((first, last)) => format!("片段 {first} 到 {last}"),
        None => "这道题没有被问到，转写里没有对应的片段".to_owned(),
    };
    format!(
        r#"# 任务：评价候选人对题目 {id} 的作答
题目：{text}
对应的转写：{segments}（追问也算在这道题里）

先看候选人实际说了什么，再对照这道题的考察意图和评分要点来评。只评这一道题，证据只从这道题对应的片段里取。

{QUESTION_RATING_SCALE}

输出 JSON：
{{
  "answered": true 或 false（候选人有没有做实质性的回答）,
  "answer_summary": "两三句话，客观概括候选人说了什么",
  "rating": 1 到 5 的数，只能是整数或者带 .5,
  "rating_reason": "为什么是这个分数，对照评分标准说；给 .5 的要说清楚它比低的一档好在哪、离高的一档差在哪",
  "strengths": [{{"point": "答得好的地方", "evidence": [证据]}}],
  "weaknesses": [{{"point": "不足或者没讲清楚的地方", "evidence": [证据]}}],
  "follow_up": "下一轮人工面试里，针对这道题最值得追问的一个问题；没有就填 null"
}}"#,
        id = group.root.id,
        text = group.root.text.trim(),
    )
}

